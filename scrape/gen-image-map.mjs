import fs from 'node:fs';

const manifest = JSON.parse(fs.readFileSync(new URL('./out/image-manifest.json', import.meta.url), 'utf8'));
const map = {};
for (const m of manifest) {
  if (!m.file) continue;
  map[m.url] = '/' + m.file;
}

// also add the standalone /img/* static assets downloaded separately
const staticAssets = {
  'https://uks.kemendikdasmen.go.id/img/logoUks.png': '/images/scraped/logoUks.png',
  'https://uks.kemendikdasmen.go.id/img/foto-7kaih.jpeg': '/images/scraped/foto-7kaih.jpeg',
  'https://uks.kemendikdasmen.go.id/img/fotoMbg.jpeg': '/images/scraped/fotoMbg.jpeg',
  'https://uks.kemendikdasmen.go.id/img/fotoCKG.png': '/images/scraped/fotoCKG.png',
  'https://uks.kemendikdasmen.go.id/img/logo-uptbercerita.jpeg': '/images/scraped/logo-uptbercerita.jpeg',
};
Object.assign(map, staticAssets);

const out = `// AUTO-GENERATED by scrape/gen-image-map.mjs — maps original uks.kemendikdasmen.go.id URLs to local downloaded assets.
export const IMAGE_MAP = ${JSON.stringify(map, null, 2)};

export function img(url) {
  if (!url) return null;
  return IMAGE_MAP[url] || IMAGE_MAP[url.replace('http://', 'https://')] || null;
}
`;

fs.writeFileSync(new URL('../src/data/imageMap.js', import.meta.url), out, 'utf8');
console.log('wrote imageMap.js with', Object.keys(map).length, 'entries');
